CREATE TABLE "audit_events" (
  "id" uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  "organization_id" text NOT NULL,
  "property_id" text,
  "actor_type" text NOT NULL,
  "actor_id" text,
  "action" text NOT NULL,
  "outcome" text NOT NULL,
  "resource_type" text NOT NULL,
  "resource_id" text,
  "source_kind" text NOT NULL,
  "source_id" text NOT NULL,
  "source_event_type" text,
  "source_event_version" integer,
  "source_context" text,
  "source_aggregate_id" text,
  "occurred_at" timestamp with time zone NOT NULL,
  CONSTRAINT "audit_events_source_uniq" UNIQUE ("organization_id", "source_kind", "source_id"),
  CONSTRAINT "audit_events_organization_id_valid" CHECK ("organization_id" ~ '^[A-Za-z0-9][A-Za-z0-9_.:@/-]{0,254}$'),
  CONSTRAINT "audit_events_property_id_valid" CHECK ("property_id" ~ '^[A-Za-z0-9][A-Za-z0-9_.:@/-]{0,254}$'),
  CONSTRAINT "audit_events_actor_id_valid" CHECK ("actor_id" ~ '^[A-Za-z0-9][A-Za-z0-9_.:@/-]{0,254}$'),
  CONSTRAINT "audit_events_resource_id_valid" CHECK ("resource_id" ~ '^[A-Za-z0-9][A-Za-z0-9_.:@/-]{0,254}$'),
  CONSTRAINT "audit_events_source_id_valid" CHECK ("source_id" ~ '^[A-Za-z0-9][A-Za-z0-9_.:@/-]{0,254}$'),
  CONSTRAINT "audit_events_source_aggregate_id_valid" CHECK ("source_aggregate_id" ~ '^[A-Za-z0-9][A-Za-z0-9_.:@/-]{0,254}$'),
  CONSTRAINT "audit_events_action_valid" CHECK ("action" ~ '^[a-z][a-z0-9_.:-]{0,79}$'),
  CONSTRAINT "audit_events_resource_type_valid" CHECK ("resource_type" ~ '^[a-z][a-z0-9_.:-]{0,39}$'),
  CONSTRAINT "audit_events_source_event_type_valid" CHECK ("source_event_type" ~ '^[a-z][a-z0-9_.:-]{0,127}$'),
  CONSTRAINT "audit_events_source_context_valid" CHECK ("source_context" ~ '^[a-z][a-z0-9_.:-]{0,127}$'),
  CONSTRAINT "audit_events_actor_type_valid" CHECK ("actor_type" ~ '^(user|system|operator|service|public)$'),
  CONSTRAINT "audit_events_actor_attribution_valid" CHECK ("actor_type" !~ '^(system|public)$' OR "actor_id" IS NULL),
  CONSTRAINT "audit_events_outcome_valid" CHECK ("outcome" ~ '^(succeeded|denied|failed)$'),
  CONSTRAINT "audit_events_source_valid" CHECK (("source_kind" = 'domain_fact' AND "source_event_type" IS NOT NULL AND "source_event_version" IS NOT NULL AND "source_event_version" >= 1 AND "source_context" IS NOT NULL AND "source_aggregate_id" IS NOT NULL) OR ("source_kind" ~ '^(policy_decision|interactive_command|worker_command|operator_command|history_access|history_lifecycle)$' AND "source_event_type" IS NULL AND "source_event_version" IS NULL AND "source_context" IS NULL AND "source_aggregate_id" IS NULL))
);
