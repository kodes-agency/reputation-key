CREATE TABLE "work_items" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "organization_id" varchar(255) NOT NULL,
  "subject_id" text NOT NULL,
  "kind" text NOT NULL,
  "idempotency_key" text NOT NULL,
  "recovery" text NOT NULL,
  "state" text DEFAULT 'pending' NOT NULL,
  "due_at" timestamptz NOT NULL,
  "dispatch_after" timestamptz NOT NULL,
  "dispatch_sequence" integer DEFAULT 0 NOT NULL,
  "attempts" integer DEFAULT 0 NOT NULL,
  "max_attempts" integer DEFAULT 8 NOT NULL,
  "lease_token" uuid,
  "lease_expires_at" timestamptz,
  "error_code" text,
  "operator_id" text,
  "operator_reason" text,
  "created_at" timestamptz DEFAULT now() NOT NULL,
  "updated_at" timestamptz DEFAULT now() NOT NULL,
  "completed_at" timestamptz,
  CONSTRAINT "work_items_idempotency_unique" UNIQUE ("organization_id", "kind", "idempotency_key"),
  CONSTRAINT "work_items_state_check" CHECK ("state" IN ('pending', 'running', 'succeeded', 'quarantined', 'uncertain', 'cancelled', 'discarded')),
  CONSTRAINT "work_items_recovery_check" CHECK ("recovery" IN ('retry', 'read_back')),
  CONSTRAINT "work_items_attempts_check" CHECK ("attempts" >= 0 AND "max_attempts" BETWEEN 1 AND 100 AND "attempts" <= "max_attempts" AND "dispatch_sequence" >= 0),
  CONSTRAINT "work_items_lease_check" CHECK (("state" = 'running' AND "lease_token" IS NOT NULL AND "lease_expires_at" IS NOT NULL) OR ("state" <> 'running' AND "lease_token" IS NULL AND "lease_expires_at" IS NULL)),
  CONSTRAINT "work_items_completion_check" CHECK (("state" IN ('succeeded', 'cancelled', 'discarded')) = ("completed_at" IS NOT NULL)),
  CONSTRAINT "work_items_error_check" CHECK ("error_code" IS NULL OR "error_code" IN ('lease_expired', 'attempts_exhausted', 'handler_failed', 'uncertain_write')),
  CONSTRAINT "work_items_identity_check" CHECK (length("kind") BETWEEN 1 AND 160 AND length("idempotency_key") BETWEEN 1 AND 255 AND length("subject_id") BETWEEN 1 AND 255 AND length("organization_id") > 0)
);
