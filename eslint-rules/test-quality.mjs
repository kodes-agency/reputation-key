const report = (context, node, detail) =>
  context.report({ node, messageId: 'quality', data: { detail } })
const meta = { type: 'problem', schema: [], messages: { quality: '{{detail}}' } }
const registered = new Map(SKIP_REGISTER.map((entry) => [entry.file, entry]))

export default {
  rules: {
    checks: {
      meta,
      create(context) {
        if (!TEST_FILE.test(context.filename)) return {}
        return {
          Program(node) {
            const file = relative(context.cwd, context.filename).split('\\').join('/')
            let skipHits = 0
            context.sourceCode.lines.forEach((line, index) => {
              for (const detail of lineFailures(line, `${file}:${index + 1}`))
                report(context, node, detail)
              if (!isSkipSite(line)) return
              skipHits += 1
              if (!registered.has(file))
                report(context, node, `${file}:${index + 1}: unregistered disabled test`)
            })
            const entry = registered.get(file)
            if (entry) {
              for (const detail of registerFailures(
                [entry],
                new Map([[file, skipHits]]),
                new Date().toISOString().slice(0, 10),
              ))
                report(context, node, detail)
            }
          },
        }
      },
    },
    // The full lint also audits absent files, stale entries and the pinned
    // runtime. Linting only an edited test still runs its local quality checks.
    register: {
      meta,
      create(context) {
        return {
          Program(node) {
            const hits = new Map()
            for (const entry of SKIP_REGISTER) {
              try {
                const lines = readFileSync(
                  resolve(context.cwd, entry.file),
                  'utf8',
                ).split('\n')
                hits.set(entry.file, lines.filter(isSkipSite).length)
              } catch {
                report(context, node, `${entry.file}: registered test file is missing`)
              }
            }
            for (const detail of registerFailures(
              SKIP_REGISTER,
              hits,
              new Date().toISOString().slice(0, 10),
            ))
              report(context, node, detail)
            const runtime = {
              node: readFileSync(resolve(context.cwd, '.nvmrc'), 'utf8').trim(),
              icu: '78.3',
              unicode: '17.0',
            }
            const drift = Object.entries(runtime).filter(
              ([key, value]) => process.versions[key] !== value,
            )
            if (drift.length > 0 && process.env.ALLOW_RUNTIME_DRIFT !== '1') {
              report(
                context,
                node,
                `Runtime-fenced tests require ${JSON.stringify(runtime)}; use the pinned runtime.`,
              )
            } else if (drift.length > 0) {
              process.stderr.write(
                '[test-quality] ALLOW_RUNTIME_DRIFT=1: runtime-fenced tests did not run.\n',
              )
            }
          },
        }
      },
    },
  },
}
