// Every durable outbox consumer, defined once.
//
// DURABLE_CONSUMERS holds each durable consumer by name with the file that
// registers it, the consumer-module row (./consumer-entry-points.ts) it is
// authorized under, and the events it receives; every one is required, so worker
// readiness and dispatcher delivery refuse a deployment in which one is not
// registered, and name it. EVENT_TYPES lists the event types the outbox routes.
//
// The event/job catalogue (EVENT_FAMILY_ROWS) is derived from these tables.

export type DurableConsumer = Readonly<{
  /** Consumer name, e.g. 'inbox.on-review-created'. */
  name: string
  /** Repo-relative file containing the registerConsumer call. */
  module: string
  /** The consumer-module row (CONSUMER_ENTRY_POINTS) it is authorized under. */
  entryPoint: string
  /** Event types the consumer receives. */
  on: ReadonlyArray<string>
}>

/** The consumers one file registers: [name, entry-point row, events it receives]. */
function consumersIn(
  module: string,
  entries: ReadonlyArray<readonly [string, string, ReadonlyArray<string>]>,
): ReadonlyArray<DurableConsumer> {
  return entries.map(([name, entryPoint, on]) => ({ name, module, entryPoint, on }))
}

